// Deploys the Apps Script project as two web apps that share one codebase:
//   public: access ANYONE_ANONYMOUS (guest JSON API)
//   admin:  access MYSELF           (owner-only admin UI)
// Deployment IDs are pinned in .env.local so the /exec URLs never change.
// Also writes docs/config.js and docs/slots.js for the GitHub Pages guest page.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const gas = path.join(root, 'gas');
const envFile = path.join(root, '.env.local');
const GUEST_BASE = 'https://takos-mone.github.io/schedule-with-shimono/';

const readEnv = () => Object.fromEntries(
  (fs.existsSync(envFile) ? fs.readFileSync(envFile, 'utf8') : '').split('\n')
    .filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
);
const writeEnv = (env) => fs.writeFileSync(envFile, Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n') + '\n');
const execUrl = (id) => `https://script.google.com/macros/s/${id}/exec`;

function clasp(...args) {
  const out = execFileSync('npx', ['clasp', ...args], { cwd: root, encoding: 'utf8' });
  process.stdout.write(out);
  return out;
}

function writeGeneratedFiles(env) {
  const slots = fs.readFileSync(path.join(root, 'shared/slots.js'), 'utf8');
  fs.writeFileSync(path.join(gas, 'slots.js'), slots);
  fs.writeFileSync(path.join(gas, 'SlotsClient.html'), `<script>\n${slots}\n</script>\n`);
  fs.writeFileSync(path.join(gas, 'Env.js'), `// Generated by scripts/deploy.mjs\nvar ENV = ${JSON.stringify({
    PUBLIC_URL: env.PUBLIC_DEPLOYMENT_ID ? execUrl(env.PUBLIC_DEPLOYMENT_ID) : '',
    ADMIN_URL: env.ADMIN_DEPLOYMENT_ID ? execUrl(env.ADMIN_DEPLOYMENT_ID) : '',
    GUEST_BASE,
  }, null, 2)};\n`);
}

function setAccess(access) {
  const file = path.join(gas, 'appsscript.json');
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  manifest.webapp.access = access;
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + '\n');
}

function deployTarget(name, access, id) {
  setAccess(access);
  clasp('push', '-f');
  const out = id ? clasp('deploy', '-i', id, '-d', name) : clasp('deploy', '-d', name);
  const m = out.match(/- (\S+) @\d+/);
  if (!m) throw new Error(`could not read deployment id for ${name}`);
  return m[1];
}

if (!fs.existsSync(path.join(root, '.clasp.json'))) {
  console.error('No .clasp.json. Run: npx clasp create --type standalone --title "日程調整 with 下野" --rootDir gas');
  process.exit(1);
}

const env = readEnv();
const firstRun = !env.PUBLIC_DEPLOYMENT_ID || !env.ADMIN_DEPLOYMENT_ID;
if (firstRun) {
  // Create both deployments once so their URLs exist, then redeploy with the URLs baked into Env.js.
  writeGeneratedFiles(env);
  env.PUBLIC_DEPLOYMENT_ID ||= deployTarget('public', 'ANYONE_ANONYMOUS');
  env.ADMIN_DEPLOYMENT_ID ||= deployTarget('admin', 'MYSELF');
  writeEnv(env);
}
writeGeneratedFiles(env);
deployTarget('public', 'ANYONE_ANONYMOUS', env.PUBLIC_DEPLOYMENT_ID);
deployTarget('admin', 'MYSELF', env.ADMIN_DEPLOYMENT_ID);
setAccess('MYSELF'); // keep the committed manifest on the safe setting

fs.writeFileSync(path.join(root, 'docs/config.js'),
  `// Generated by scripts/deploy.mjs. The public Apps Script URL is not a secret.\nwindow.CONFIG = { API_URL: '${execUrl(env.PUBLIC_DEPLOYMENT_ID)}' };\n`);
fs.copyFileSync(path.join(root, 'shared/slots.js'), path.join(root, 'docs/slots.js'));

console.log(`\npublic: ${execUrl(env.PUBLIC_DEPLOYMENT_ID)}\nadmin:  ${execUrl(env.ADMIN_DEPLOYMENT_ID)}\nguest:  ${GUEST_BASE}?l=<link id>`);
